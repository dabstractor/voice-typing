# (name, wav path, reference text) — canonical strings from tests/make_test_audio.sh
FIXTURES = [
    ("utt_simple", os.path.join(REPO, "tests/out/utt_simple.wav"),
     "The quick brown fox jumps over the lazy dog."),
    ("utt_pause", os.path.join(REPO, "tests/out/utt_pause.wav"),
     "I want to test whether this system keeps listening after a pause."),
    ("utt_multi", os.path.join(REPO, "tests/out/utt_multi.wav"),
     "The weather looks good today. I need to buy some groceries. Let us meet at the cafe."),
    ("utt_punct", os.path.join(REPO, "tests/out/utt_punct.wav"),
     "Hello, world! Does punctuation, like commas, question marks? It should."),
]

CHUNK_S = 0.1  # audio feed granularity (seconds)

VOICE_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "voice")


def discover_wavs() -> list[tuple[str, str, str]]:
    """Lab fixtures + user voice clips. Voice clips live in tools/asr-lab/voice/
    as name.wav + name.txt (the reference text read aloud to record name.wav).
    """
    out = list(FIXTURES)
    if os.path.isdir(VOICE_DIR):
        for wav in sorted(os.listdir(VOICE_DIR)):
            if not wav.endswith(".wav"):
                continue
            stem = wav[:-4]
            ref_p = os.path.join(VOICE_DIR, stem + ".txt")
            if os.path.exists(ref_p):
                ref = open(ref_p).read().strip()
                out.append((f"voice_{stem}", os.path.join(VOICE_DIR, wav), ref))
    return out


def wav_duration(path: str) -> float:
    import wave
    with wave.open(path) as w:
        return w.getnframes() / w.getframerate()


def wav_chunks(path: str, chunk_s: float = CHUNK_S):
    """Yield (offset_seconds, bytes) chunks of 16-bit mono PCM at native rate."""
    import wave
    with wave.open(path) as w:
        rate, n = w.getframerate(), w.getnframes()
        step = int(rate * chunk_s)
        off = 0.0
        while True:
            frames = w.readframes(step)
            if not frames:
                break
            yield off, frames
            off += chunk_s


def pcm_float_chunks(path: str, chunk_s: float = CHUNK_S):
    """Yield (offset_seconds, list[float] samples in [-1,1]) for engines wanting floats."""
    import array

    for off, raw in wav_chunks(path, chunk_s):
        a = array.array("h")
        a.frombytes(raw)
        yield off, [s / 32768.0 for s in a]


def vram_mib() -> int:
    try:
        out = subprocess.run(
            ["nvidia-smi", "--query-gpu=memory.used", "--format=csv,noheader,nounits"],
            capture_output=True, text=True, timeout=10)
        return int(out.stdout.strip().splitlines()[0])
    except Exception:
        return -1


def norm_words(s: str) -> list[str]:
    s = unicodedata.normalize("NFKC", s).lower()
    return re.sub(r"[^a-z0-9' ]", " ", s).split()


def similarity(hyp: str, ref: str) -> float:
    import difflib
    h, r = norm_words(hyp), norm_words(ref)
    if not r:
        return 0.0
    return round(difflib.SequenceMatcher(a=h, b=r).ratio(), 4)


def wer(hyp: str, ref: str) -> float:
    """Word error rate: (sub + ins + del) / ref words, via SequenceMatcher opcodes."""
    import difflib
    h, r = norm_words(hyp), norm_words(ref)
    if not r:
        return 1.0
    bad = 0
    sm = difflib.SequenceMatcher(a=h, b=r, autojunk=False)
    for tag, i1, i2, j1, j2 in sm.get_opcodes():
        if tag != "equal":
            bad += max(i2 - i1, j2 - j1)
    return round(bad / len(r), 4)


def summarize_emissions(events, final_text, ref, dur_s, feed_start, last_audio_at):
    """Turn a list of (emit_time, partial_text) into the common metrics.

    `events` must be in feed order; emit_time is wall clock. A word's audio
    offset is unknown post-hoc, so feedback latency is approximated as
    emit_time - feed_start - (audio offset of the word's first appearance in a
    time-aligned emission). Adapters that know word offsets can pass events as
    (emit_time, audio_offset_s, partial_text); this function handles both.
    """
    import statistics

    words_final = norm_words(final_text)
    # first-seen time per normalized word occurrence index (approximate: count-
    # based matching of the running partial against the final word sequence)
    final_positions = {}
    counts: dict[str, int] = {}
    for i, w in enumerate(words_final):
        k = (w, counts.get(w, 0))
        counts[w] = counts.get(w, 0) + 1
        final_positions[k] = i

    seen: dict[tuple, float] = {}
    retracted: set[tuple] = set()
    for ev in events:
        emit_t, text = ev[0], ev[-1]
        running = norm_words(text)
        c: dict[str, int] = {}
        present = set()
        for w in running:
            k = (w, c.get(w, 0))
            c[w] = c.get(w, 0) + 1
            present.add(k)
            if k not in seen:
                seen[k] = emit_t
        # words seen earlier but no longer present => retraction/wobble (once per word)
        retracted.update(k for k in seen if k not in present)

    # audio offset of word i, linear approx: final words spread over dur_s
    fb = []
    for k, t in seen.items():
        i = final_positions.get(k)
        if i is None:
            continue
        audio_off = dur_s * (i + 1) / max(1, len(words_final))
        lag = t - feed_start - audio_off
        if lag >= -0.05:  # tolerate tiny clock skew
            fb.append(max(0.0, lag))
    ttfd = min((t - feed_start for k, t in seen.items() if k in final_positions),
               default=None)
    return {
        "ttfd_s": round(ttfd, 3) if ttfd is not None else None,
        "feedback_ms_med": round(1000 * statistics.median(fb)) if fb else None,
        "feedback_ms_p95": round(1000 * sorted(fb)[int(0.95 * len(fb)) - 1 if len(fb) > 1 else 0]) if fb else None,
        "wobble_n": len(retracted),
        "final_lag_s": round(events[-1][0] - last_audio_at, 3) if events else None,
        "wer": wer(final_text, ref),
        "sim": similarity(final_text, ref),
        "final_text": final_text,
    }


def emit_json(result: dict) -> None:
    print(json.dumps(result))
