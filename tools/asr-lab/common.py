"""Shared harness pieces for the offline ASR lab.

Every adapter reports the SAME metrics, computed from a stream of word-emission
events produced while feeding audio at REAL-TIME pace:

  load_s            engine/model load wall time (warm cache)
  vram_delta_mib    nvidia-smi memory.used delta across load (0 for CPU engines)
  per-wav:
    dur_s             audio duration
    ttfd_s            time-to-first-word: wall clock from audio START to the
                      first still-committed word appearing on screen
    feedback_ms       median/95p wall-clock lag between a word's audio offset
                      and its emission (the "phone feel" metric)
    wobble_n          emissions that were later retracted/changed (revisions)
    final_lag_s       wall clock from LAST audio chunk fed to final text
    sim               SequenceMatcher word-similarity vs ground truth

Feeding at real-time pace is representative because every engine here runs at
RTF << 1 — the live experience equals this simulation modulo mic/VAD capture.

Ground truths are the repo's e2e fixtures (tests/out/*.wav, generated by
tests/make_test_audio.sh — see that script for the canonical texts).
"""
from __future__ import annotations

import os
REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))

import json
